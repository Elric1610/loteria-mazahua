-- Lotería Interactiva Mazahua · estructura y registros (MySQL / MariaDB)
-- Importar con phpMyAdmin (pestaña «Importar») o:  mysql -u root < database/loteria_mazahua.sql
-- Es seguro volver a importarlo: usa IF NOT EXISTS / INSERT IGNORE y no borra nada.
-- El nombre de la base debe coincidir con DB_NAME de backend/app/config.py.
-- La tabla «usuarios» queda vacía: la API crea al docente inicial en su primer arranque.

CREATE DATABASE IF NOT EXISTS loteria_mazahuaa CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE loteria_mazahuaa;
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS tarjetas (
  numero      INT          NOT NULL PRIMARY KEY,
  uid         VARCHAR(32)  NULL UNIQUE,          -- UID de la tarjeta RFID
  nombre_es   VARCHAR(100) NOT NULL,
  descripcion TEXT         NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS nombres_mazahua (
  numero_tarjeta INT          NOT NULL PRIMARY KEY,
  nombre_maz     VARCHAR(150) NOT NULL,
  FOREIGN KEY (numero_tarjeta) REFERENCES tarjetas(numero)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS imagenes (
  numero_tarjeta INT          NOT NULL PRIMARY KEY,
  ruta           VARCHAR(255) NOT NULL,
  FOREIGN KEY (numero_tarjeta) REFERENCES tarjetas(numero)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS audios (
  id             INT AUTO_INCREMENT PRIMARY KEY,
  numero_tarjeta INT          NOT NULL,
  idioma         ENUM('es','maz') NOT NULL,      -- es = español, maz = mazahua
  ruta           VARCHAR(255) NOT NULL,
  UNIQUE KEY uq_audio (numero_tarjeta, idioma),
  FOREIGN KEY (numero_tarjeta) REFERENCES tarjetas(numero)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS usuarios (
  id            INT AUTO_INCREMENT PRIMARY KEY,
  username      VARCHAR(50)  NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  nombre        VARCHAR(100) NOT NULL DEFAULT 'Docente'
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS videos (
  id          INT AUTO_INCREMENT PRIMARY KEY,
  titulo      VARCHAR(150) NOT NULL,
  url         VARCHAR(255) NOT NULL,
  descripcion TEXT         NULL
) ENGINE=InnoDB;

